PAGES = {"PRIVACY": PRIVACY, "TERMS": TERMS, "INSTRUCTIONS": INSTRUCTIONS, "FAQ": FAQ}


def _first_draft() -> dict[str, str]:
    first = importlib.import_module("content_services.migrations.0003_seed_legal_documents")
    return {key: getattr(first, key) for key in PAGES}


def publish(apps, schema_editor):
    LegalDocument = apps.get_model("content_services", "LegalDocument")
    first = _first_draft()
    now = timezone.now()
    for key, body in PAGES.items():
        active = LegalDocument.objects.filter(key=key, active=True).first()
        # Only the untouched first draft is replaced; an operator's own version stays.
        if active is None or active.version != 1 or active.body_ar != first[key]:
            continue
        newest = LegalDocument.objects.filter(key=key).order_by("-version").first()
        LegalDocument.objects.filter(pk=active.pk).update(active=False)
        LegalDocument.objects.create(
            key=key,
            kind=active.kind,
            title_ar=active.title_ar,
            body_ar=body,
            version=newest.version + 1,
            active=True,
            published_at=now,
        )


def unpublish(apps, schema_editor):
    LegalDocument = apps.get_model("content_services", "LegalDocument")
    for key, body in PAGES.items():
        mine = LegalDocument.objects.filter(key=key, active=True, body_ar=body).first()
        if mine is None:
            continue
        mine.delete()
        LegalDocument.objects.filter(key=key, version=1).update(active=True)


